function Invoke-NativeTool([string]$Executable,[string[]]$Arguments,[hashtable]$Environment) {
 $start=New-Object Diagnostics.ProcessStartInfo
 $start.FileName=$Executable;$start.WorkingDirectory=Split-Path $Executable -Parent
 # All arguments are generated paths/flags, never free-form commands.
 $quoted=foreach($arg in $Arguments){if($arg.Contains('"') -or $arg.EndsWith('\')){throw 'Unsupported tool argument'};'"'+$arg+'"'}
 $start.Arguments=$quoted -join ' ';$start.UseShellExecute=$false;$start.CreateNoWindow=$true
 $start.RedirectStandardOutput=$true;$start.RedirectStandardError=$true
 foreach($key in $Environment.Keys){$start.EnvironmentVariables[$key]=[string]$Environment[$key]}
 $process=New-Object Diagnostics.Process;$process.StartInfo=$start
 try{
  if(!$process.Start()){throw 'Could not start native verification'}
  $stdout=$process.StandardOutput.ReadToEndAsync();$stderr=$process.StandardError.ReadToEndAsync()
  if(!$process.WaitForExit(120000)){$process.Kill();$process.WaitForExit();throw 'Native verification timed out'}
  $out=$stdout.GetAwaiter().GetResult();$err=$stderr.GetAwaiter().GetResult()
  Write-Host ('NATIVE TOOL EXITED: pid='+$process.Id+' exit='+$process.ExitCode+' executable='+$Executable)
  if($process.ExitCode -ne 0){throw ('Native verification failed: '+$err)}
  return $out
 }finally{$process.Dispose()}
}
# Configuration files owned by the release package. Player state (native-data)
# and machine-local selectors (.env) are never part of this set.
$script:NativeConfigNames=@('host.json','gameplay.lua','economy.lua')
function Get-PackageNativeConfig([string]$Release) {
 # A complete set means the package owns the live configuration; no file means a
 # legacy package still needs the one-way migration. A partial set is a build
 # defect and must never be merged into the live state.
 $present=@($script:NativeConfigNames|Where-Object {Test-Path -LiteralPath (Join-Path $Release $_)})
 if($present.Count -eq 0){return ''}
 if($present.Count -ne $script:NativeConfigNames.Count){throw ('Package configuration is incomplete: '+($present -join ', '))}
 return $Release
}
function Write-NativeRulesDoc([string]$Shared,[switch]$Ephemeral) {
 $path=Join-Path $Shared 'RULES.md'
 $dataRule=if($Ephemeral){'* Rooms exist only in process memory and each restart starts with empty rooms. Historical native-data remains for reference; this deployment does not read, copy, restore or delete it.'}else{'* native-data is live player state. It is never part of a release and is never replaced.'}
 $text=@(
  '# Managed configuration rules'
  ''
  'This file is generated by the deployment adapter. Do not edit it.'
  ''
  '* Existing host.json, gameplay.lua and economy.lua are authoritative server configuration.'
  '* Deployments preserve their actual values; package defaults only initialize a new server.'
  '* Legacy server.json is migrated with hash verification before the first native deployment.'
  '* Server host/gameplay/economy configuration is managed through the manager; deployments preserve the actual server values.'
  $dataRule
  '* .env keeps machine-local selectors; it is preserved across deployments.'
  ''
 ) -join "`r`n"
 if((Test-Path -LiteralPath $path) -and ((Get-NativeReleaseHash $path) -eq (Get-NativeReleaseHashOfBytes ([Text.Encoding]::UTF8.GetBytes($text))))){return}
 [IO.File]::WriteAllText($path,$text,[Text.UTF8Encoding]::new($false))
}
function Get-NativeReleaseHashOfBytes([byte[]]$Bytes) {
 $sha=[Security.Cryptography.SHA256]::Create()
 try{return ([BitConverter]::ToString($sha.ComputeHash($Bytes))).Replace('-','').ToLowerInvariant()}
 finally{$sha.Dispose()}
}
function Test-NativeEphemeralIdentity($Identity) {
 if($Identity.PSObject.Properties.Name -notcontains 'room_state_mode'){return $false}
 if($Identity.room_state_mode -cne 'ephemeral'){throw 'Unsupported native room state mode'}
 return $true
}
function Assert-NativeEphemeralProof($Proof) {
 if($Proof.PSObject.Properties.Name -notcontains 'room_state_mode' -or $Proof.room_state_mode -cne 'ephemeral' -or $Proof.PSObject.Properties.Name -notcontains 'history_loaded' -or $Proof.history_loaded -isnot [bool] -or $Proof.history_loaded -cne $false){throw 'Native ephemeral proof must confirm room_state_mode=ephemeral and history_loaded=false'}
}

# Redis versions stay exactly DLL-bound. A program upgrade may clone the actual
# immutable JSON snapshot, validate it with the candidate DLL, and publish that
# new version only inside this stopped-service maintenance transaction.
function Assert-NativeRedisSummary($Version) {
 if($null -eq $Version -or $Version.PSObject.Properties.Name -notcontains 'schema_version' -or $Version.schema_version -notin @(1,2) -or
    [string]$Version.id -cnotmatch '^[a-f0-9]{32}$' -or [string]$Version.sha256 -cnotmatch '^[a-f0-9]{64}$' -or
    [string]$Version.dll_sha256 -cnotmatch '^[a-f0-9]{64}$'){throw 'Invalid Redis configuration identity; no automatic publication allowed'}
}
function Assert-NativeRedisSummaryEqual($Actual,$Expected) {
 Assert-NativeRedisSummary $Actual;Assert-NativeRedisSummary $Expected
 foreach($name in @('schema_version','id','sha256','dll_sha256')){
  if([string]$Actual.$name -cne [string]$Expected.$name){throw ('Redis configuration identity changed: '+$name+'; recovery held')}
 }
}
function Get-NativeRedisOverrides($State) {
 # Agent process variables need not be the Windows game's effective variables.
 # An explicit source override is ambiguous even if .env says files; reject it
 # before inspecting any Redis. Other overrides matter only in Redis mode.
 $found=@()
 foreach($scope in @('Machine','Process')){
  $variables=[Environment]::GetEnvironmentVariables([EnvironmentVariableTarget]$scope)
  foreach($name in $variables.Keys){if([string]$name -match '^REDIS_'){$found+=($scope+':'+$name)}}
 }
 if($State.service_name -notmatch '^[A-Za-z0-9_.-]+$'){throw 'Invalid game service name for configuration inspection'}
 $key=[Microsoft.Win32.Registry]::LocalMachine.OpenSubKey(('SYSTEM\CurrentControlSet\Services\'+$State.service_name),$false)
 if($null -eq $key){throw 'Game service environment is unavailable'}
 try{
  foreach($entry in @($key.GetValue('Environment',@()))){
   if([string]$entry -match '^(REDIS_[^=]*)='){$found+=('Service:'+$Matches[1])}
  }
 }finally{$key.Dispose()}
 if(@($found|Where-Object {$_ -match ':REDIS_CONFIG_SOURCE$'}).Count){throw 'REDIS_CONFIG_SOURCE overrides exist outside shared/.env; reconcile the game service and Agent source before automatic configuration deployment'}
 return $found
}
function Invoke-NativeRedisTool([string]$Release,[string]$Shared,[string[]]$Arguments) {
 Assert-ChildPath $layout.Releases $Release
 $null=Get-MaintenanceTree $Release
 $identity=Test-NativeReleaseIdentity $Release -AllowHistorical
 $toolEntries=@($identity.files|Where-Object {$_.path -ceq 'redisctl.exe'})
 if($toolEntries.Count -ne 1){throw 'Verified release does not contain a manifest-bound redisctl.exe'}
 $tool=Join-Path $Release 'redisctl.exe'
 if((Get-NativeReleaseHash $tool) -cne $toolEntries[0].sha256){throw 'Redis tool identity changed'}
 $environmentFile=Join-Path $Shared '.env'
 $info=Get-Item -LiteralPath $environmentFile -Force -ErrorAction Stop
 if($info.PSIsContainer -or $info.Length -gt 1MB -or ($info.Attributes -band [IO.FileAttributes]::ReparsePoint)){throw 'Explicit Redis environment must be a regular bounded file'}
 $start=New-Object Diagnostics.ProcessStartInfo
 $start.FileName=$tool;$start.WorkingDirectory=$Release;$start.UseShellExecute=$false;$start.CreateNoWindow=$true
 $start.RedirectStandardOutput=$true;$start.RedirectStandardError=$true
 $start.StandardOutputEncoding=[Text.UTF8Encoding]::new($false,$true);$start.StandardErrorEncoding=[Text.UTF8Encoding]::new($false,$true)
 foreach($name in @($start.EnvironmentVariables.Keys)){if([string]$name -match '^REDIS_'){$start.EnvironmentVariables.Remove([string]$name)}}
 $fixed=@{ENV_FILE=$environmentFile;SERVER_CONFIG_FILE=(Join-Path $Shared 'host.json');GAMECORE_DLL=(Join-Path $Release 'gamecore.dll');GAMECORE_SHA256=$identity.dll_sha256;COMBAT_CONTENT_DIR=(Join-Path $Release 'configs/combat');LOG_DIR=(Join-Path $Shared 'logs')}
 foreach($name in $fixed.Keys){$start.EnvironmentVariables[$name]=[string]$fixed[$name]}
 $quoted=foreach($argument in $Arguments){if($argument -cnotmatch '^[a-z0-9-]+$'){throw 'Invalid fixed Redis tool argument'};'"'+$argument+'"'}
 $start.Arguments=$quoted -join ' '
 $process=New-Object Diagnostics.Process;$process.StartInfo=$start
 $environmentLock=$null
 try{
  $environmentLock=[IO.File]::Open($environmentFile,[IO.FileMode]::Open,[IO.FileAccess]::Read,[IO.FileShare]::Read)
  if(!$process.Start()){throw 'Could not start verified Redis configuration tool'}
  $stdout=$process.StandardOutput.ReadToEndAsync();$stderr=$process.StandardError.ReadToEndAsync()
  if(!$process.WaitForExit(120000)){$process.Kill();$process.WaitForExit();throw 'Redis configuration operation timed out; its result may be unknown, recover this checkpoint before retrying'}
  $out=$stdout.GetAwaiter().GetResult();$err=$stderr.GetAwaiter().GetResult()
  # Tool output can contain database diagnostics. Never copy raw stderr, .env,
  # credentials or unbounded response bodies into the deployment log.
  if($process.ExitCode -ne 0 -or $out.Length -gt 65536 -or $err.Length -gt 65536){throw ('Redis configuration operation failed: '+$Arguments[0]+'; publication outcome must be inspected by checkpoint recovery')}
  try{$result=$out|ConvertFrom-Json -ErrorAction Stop}catch{throw 'Redis configuration tool returned invalid JSON'}
  if($null -eq $result -or $result.PSObject.Properties.Name -notcontains 'status' -or $result.status -eq 'error'){throw ('Redis configuration operation rejected: '+$Arguments[0]+'; no unchecked result will be used')}
  return $result
 }finally{if($null -ne $environmentLock){$environmentLock.Dispose()};$process.Dispose()}
}
function Get-NativeRedisActive([string]$Release,[string]$Shared) {
 $status=Invoke-NativeRedisTool $Release $Shared @('status')
 if($status.status -cne 'ok' -or [string]$status.active_configuration_id -cnotmatch '^[a-f0-9]{32}$'){throw 'Redis active configuration is missing or invalid'}
 $shown=Invoke-NativeRedisTool $Release $Shared @('config-show','--version',[string]$status.active_configuration_id)
 if($shown.status -cne 'ok'){throw 'Redis active configuration cannot be read'}
 Assert-NativeRedisSummary $shown.version
 if($shown.version.id -cne $status.active_configuration_id){throw 'Redis active configuration identity differs from selected version'}
 return $shown.version
}
function Get-NativeRedisCheckpointContext($Checkpoint) {
 $hasRedis=if($Checkpoint -is [Collections.IDictionary]){$Checkpoint.Contains('redis')}else{$Checkpoint.PSObject.Properties.Name -contains 'redis'}
 $hasLayout=if($Checkpoint -is [Collections.IDictionary]){$Checkpoint.Contains('layout_version')}else{$Checkpoint.PSObject.Properties.Name -contains 'layout_version'}
 if(!$hasLayout -or $Checkpoint.layout_version -ne 4 -or $Checkpoint.kind -cne 'native-v1' -or $Checkpoint.room_state_mode -cne 'ephemeral' -or
    !$hasRedis -or $Checkpoint.redis.transaction_version -ne 1){throw 'Unsupported Redis maintenance checkpoint; recovery held'}
 $redis=$Checkpoint.redis
 Assert-NativeRedisSummary $redis.old;Assert-NativeRedisSummary $redis.target
 if($redis.old_release -cne $Checkpoint.old_state.current_version -or $redis.target_release -cne $Checkpoint.target_version -or $redis.target.dll_sha256 -cne $Checkpoint.target_dll -or
    $redis.phase -cnotin @('publish_intent','published','restoring','restored','preserved')){throw 'Redis checkpoint does not match this program transaction'}
 if([string]$redis.old_release -cnotmatch '^[A-Za-z0-9][A-Za-z0-9._-]{0,127}$' -or [string]$redis.target_release -cnotmatch '^[A-Za-z0-9][A-Za-z0-9._-]{0,127}$'){throw 'Invalid Redis checkpoint release identity'}
 $oldRelease=Join-Path $layout.Releases $redis.old_release;$targetRelease=Join-Path $layout.Releases $redis.target_release
 Assert-ChildPath $layout.Releases $oldRelease;Assert-ChildPath $layout.Releases $targetRelease
 $oldIdentity=Test-NativeReleaseIdentity $oldRelease -AllowHistorical;$targetIdentity=Test-NativeReleaseIdentity $targetRelease -AllowHistorical
 if($oldIdentity.version -cne $redis.old_release -or $oldIdentity.dll_sha256 -cne $redis.old.dll_sha256 -or $targetIdentity.version -cne $redis.target_release -or $targetIdentity.dll_sha256 -cne $redis.target.dll_sha256){throw 'Redis checkpoint release or DLL changed; recovery held'}
 $backup=Join-Path $Checkpoint.transaction 'backup-shared'
 if((Get-NativeStateTreeJSON $backup -ExcludeNativeData) -cne $Checkpoint.shared_tree -or [string]$redis.environment_sha256 -cnotmatch '^[a-f0-9]{64}$' -or (Get-NativeReleaseHash (Join-Path $backup '.env')) -cne $redis.environment_sha256){throw 'Redis recovery environment backup changed'}
 # Check live ownership before any Redis CAS. Otherwise a changed live .env
 # could make restoration publish to the old database and start in a new one.
 if($Checkpoint.phase -cin @('stopping','backed_up')){
  if((Get-NativeStateTreeJSON $layout.Shared -ExcludeNativeData) -cne $Checkpoint.shared_tree){throw 'Live shared configuration changed before activation; Redis recovery held'}
 }elseif($Checkpoint.phase -cin @('switching','activated')){
  Assert-NativeConfigTransition $layout.Shared $Checkpoint.shared_tree $Checkpoint.candidate_tree -ExcludeNativeData
 }elseif($Checkpoint.phase -ceq 'start_intent' -and $Checkpoint.may_have_served){
  # Running hosts legitimately recreate their protected discovery file. Only
  # the switch-owned configuration files must remain exactly the candidate.
  $expected=@{};foreach($entry in ($Checkpoint.candidate_tree|ConvertFrom-Json)){$expected[$entry.path]=$entry}
  foreach($name in $script:NativeSwitchFiles){
   $path=Join-Path $layout.Shared $name
   if($expected.ContainsKey($name)){
    $file=Get-Item -LiteralPath $path -Force -ErrorAction Stop
    if($expected[$name].kind -cne 'file' -or $file.PSIsContainer -or ($file.Attributes -band [IO.FileAttributes]::ReparsePoint) -or
       (Get-NativeReleaseHash $path) -cne $expected[$name].sha256){throw 'Live configuration changed after start intent; Redis recovery held'}
   }elseif(Test-Path -LiteralPath $path){throw 'Unexpected live configuration after start intent; Redis recovery held'}
  }
 }else{throw 'Redis checkpoint has an invalid program phase; recovery held'}
 if(@(Get-NativeRedisOverrides $Checkpoint.old_state).Count){throw 'Redis overrides exist outside the checkpoint environment; reconcile them before recovery'}
 return [pscustomobject]@{OldRelease=$oldRelease;TargetRelease=$targetRelease;Shared=$backup;Redis=$redis}
}
function Restore-NativeRedisConfiguration($Checkpoint) {
 $context=Get-NativeRedisCheckpointContext $Checkpoint
 Assert-NativeStopped (Read-DeploymentState -Layout $layout)
 $active=Get-NativeRedisActive $context.TargetRelease $context.Shared
 if($active.id -ceq $context.Redis.old.id){
  Assert-NativeRedisSummaryEqual $active $context.Redis.old
 }elseif($active.id -ceq $context.Redis.target.id){
  Assert-NativeRedisSummaryEqual $active $context.Redis.target
  $Checkpoint.redis.phase='restoring';Write-MaintenanceState $checkpointPath $Checkpoint
  $restored=Invoke-NativeRedisTool $context.OldRelease $context.Shared @('config-publish','--version',[string]$context.Redis.old.id,'--expected',[string]$context.Redis.target.id)
  if($restored.status -cne 'published' -or $restored.expected_previous_id -cne $context.Redis.target.id){throw 'Redis restoration receipt differs; recovery held'}
  Assert-NativeRedisSummaryEqual $restored.version $context.Redis.old
  Assert-NativeRedisSummaryEqual (Get-NativeRedisActive $context.TargetRelease $context.Shared) $context.Redis.old
 }else{throw 'Redis active configuration changed outside this deployment; automatic restoration refused'}
 $Checkpoint.redis.phase='restored';Write-MaintenanceState $checkpointPath $Checkpoint
 Write-Host ('REDIS PRE-START RECOVERY: restored configuration '+$context.Redis.old.id)
}
function Assert-NativeRedisTarget($Checkpoint) {
 $hasLayout=if($Checkpoint -is [Collections.IDictionary]){$Checkpoint.Contains('layout_version')}else{$Checkpoint.PSObject.Properties.Name -contains 'layout_version'}
 if(!$hasLayout){return}
 if($Checkpoint.layout_version -ne 4){return}
 $context=Get-NativeRedisCheckpointContext $Checkpoint
 Assert-NativeRedisSummaryEqual (Get-NativeRedisActive $context.TargetRelease $context.Shared) $context.Redis.target
}
function Assert-NativeRedisProof($Checkpoint,$Proof) {
 $hasLayout=if($Checkpoint -is [Collections.IDictionary]){$Checkpoint.Contains('layout_version')}else{$Checkpoint.PSObject.Properties.Name -contains 'layout_version'}
 if(!$hasLayout){return}
 if($Checkpoint.layout_version -ne 4){return}
 if($Proof.PSObject.Properties.Name -notcontains 'redis_configuration_version' -or $Proof.configuration_source -cne 'redis' -or
    $Proof.redis_configuration_version -cne $Checkpoint.redis.target.id){throw 'Native preflight did not accept this transaction Redis configuration'}
}
function Prepare-NativeRedisConfiguration([string]$Release,[string]$Shared,$Identity,$State,$Checkpoint) {
 if($job.action -cne 'package'){return}
 if($Identity.PSObject.Properties.Name -notcontains 'redis_configuration_rebind'){return}
 if($Identity.redis_configuration_rebind -ne 1){throw 'Unsupported Redis deployment coordination version'}
 # Every Redis read/write, including recovery, uses this one immutable backup.
 # Working .env changes only host/DLL selectors; no Redis values are rewritten.
 # Tool process selectors explicitly select the DLL being validated below.
 $Shared=Join-Path $Checkpoint.transaction 'backup-shared'
 if((Get-NativeStateTreeJSON $Shared -ExcludeNativeData) -cne $Checkpoint.shared_tree){throw 'Redis configuration environment snapshot changed'}
 $overrides=@(Get-NativeRedisOverrides $State)
 $status=Invoke-NativeRedisTool $Release $Shared @('deployment-config-status')
 if($status.status -cne 'ok' -or $status.configuration_source -cnotin @('files','redis')){throw 'Unable to determine authoritative deployment configuration source'}
 if($status.configuration_source -ceq 'files'){return}
 if($overrides.Count){throw 'Redis overrides exist outside shared/.env; automatic configuration deployment requires one unambiguous environment file'}
 if(!(Test-NativeEphemeralIdentity $Identity) -or $job.action -cne 'package' -or !$job.maintenance){throw 'Redis configuration coordination requires a package maintenance deployment'}
 Assert-NativeRedisSummary $status.version
 $oldRelease=Join-Path $layout.Releases $State.current_version
 Assert-ChildPath $layout.Releases $oldRelease
 $oldIdentity=Test-NativeReleaseIdentity $oldRelease -AllowHistorical
 if($oldIdentity.version -cne $State.current_version -or $oldIdentity.dll_sha256 -cne $status.version.dll_sha256){throw 'Published Redis configuration does not match the installed program; reconcile before deployment'}
 # Ensure rollback has a verified tool and can validate the actual old version
 # before any publication, rather than discovering this after a failed switch.
 $oldCheck=Invoke-NativeRedisTool $oldRelease $Shared @('config-validate','--version',[string]$status.version.id)
 if($oldCheck.status -cne 'validated' -or $oldCheck.validated -ne $true){throw 'Old Redis configuration is not recoverable by the installed DLL'}
 Assert-NativeRedisSummaryEqual $oldCheck.version $status.version
 $target=$status.version;$phase='preserved'
 if($status.version.dll_sha256 -cne $Identity.dll_sha256){
  $draft=Invoke-NativeRedisTool $Release $Shared @('config-rebind','--base',[string]$status.version.id,'--base-sha256',[string]$status.version.sha256)
  if($draft.status -cne 'draft_saved' -or $draft.published -ne $false -or $draft.base_version_id -cne $status.version.id -or $draft.base_sha256 -cne $status.version.sha256){throw 'Redis rebind receipt differs from the actual active configuration'}
  Assert-NativeRedisSummary $draft.version
  if($draft.version.schema_version -ne 2 -or $draft.version.base_version_id -cne $status.version.id -or $draft.version.dll_sha256 -cne $Identity.dll_sha256 -or $draft.version.id -ceq $status.version.id){throw 'Redis candidate is not bound to this configuration and DLL'}
  $target=$draft.version;$phase='publish_intent'
 }
 Assert-NativeRedisSummaryEqual (Get-NativeRedisActive $Release $Shared) $status.version
 # Layout 4 is rejected by previous workers before recovery mutates any state.
 # Both immutable identities and publication intent must reach disk first.
 $Checkpoint.layout_version=4
 $Checkpoint['redis']=[ordered]@{transaction_version=1;phase=$phase;old=$status.version;target=$target;old_release=$State.current_version;target_release=$Identity.version;environment_sha256=(Get-NativeReleaseHash (Join-Path $Checkpoint.transaction 'backup-shared/.env'))}
 Write-MaintenanceState $checkpointPath $Checkpoint
 if($phase -ceq 'publish_intent'){
  Assert-NativeStopped $State
  $null=Get-NativeRedisCheckpointContext $Checkpoint
  $published=Invoke-NativeRedisTool $Release $Shared @('config-publish','--version',[string]$target.id,'--expected',[string]$status.version.id)
  if($published.status -cne 'published' -or $published.expected_previous_id -cne $status.version.id){throw 'Redis publication receipt differs; recover this checkpoint before retrying'}
  Assert-NativeRedisSummaryEqual $published.version $target
  $Checkpoint.redis.phase='published';Write-MaintenanceState $checkpointPath $Checkpoint
  Write-Host ('REDIS CONFIG REBOUND: '+$status.version.id+' -> '+$target.id+'; JSON values preserved, target DLL verified')
 }else{Write-Host ('REDIS CONFIG PRESERVED: '+$target.id+'; DLL binding unchanged')}
 Assert-NativeRedisTarget $Checkpoint
}
function Test-NativeWorkingCopy([string]$Release,[string]$Shared,$Identity,[switch]$ExcludeNativeData) {
 Assert-MaintenanceSeparate @($layout.Shared,$Shared)
 if([bool]$ExcludeNativeData -ne (Test-NativeEphemeralIdentity $Identity)){throw 'Native preflight snapshot mode differs from release identity'}
 if($ExcludeNativeData -and (Test-Path -LiteralPath (Join-Path $Shared 'native-data'))){throw 'Ephemeral preflight copy must not contain historical native-data'}
 $dataBefore=@{};foreach($e in @(Get-MaintenanceTree $Shared -ExcludeLogs -ExcludeNativeData:$ExcludeNativeData)){$dataBefore[$e.path]=$e}
 $environment=@{SERVER_CONFIG_FILE=(Join-Path $Shared 'host.json');GAMECORE_DLL=(Join-Path $Release 'gamecore.dll');GAMECORE_SHA256=$Identity.dll_sha256;COMBAT_CONTENT_DIR=(Join-Path $Release 'configs/combat');ENV_FILE=(Join-Path $Shared '.env');LOG_DIR=(Join-Path $Shared 'logs')}
 $proof=(Invoke-NativeTool (Join-Path $Release 'server.exe') @('-preflight') $environment)|ConvertFrom-Json
 if($proof.preflight -cne 'passed' -or $proof.listener_started -ne $false -or $proof.gameplay_commands_executed -ne 0 -or $proof.dll_sha256 -cne $Identity.dll_sha256 -or $proof.module.build_id -cne $Identity.dll_build_id -or $proof.transport_profile -cne 'warcraft-round-v1'){throw 'Native recovery proof differs from target'}
 if($Identity.PSObject.Properties.Name -contains 'redis_configuration_rebind'){
  if($Identity.redis_configuration_rebind -ne 1 -or $proof.PSObject.Properties.Name -notcontains 'runtime_identity'){throw 'Coordinated deployment requires actual preflight runtime identity'}
  $runtimeAudit=Get-Content -LiteralPath (Join-Path $Release 'verification.json') -Raw -Encoding UTF8|ConvertFrom-Json
  Assert-NativeRuntimeContract $proof $runtimeAudit
 }
 if($ExcludeNativeData){
  Assert-NativeEphemeralProof $proof
  if(Test-Path -LiteralPath (Join-Path $Shared 'native-data')){throw 'Ephemeral preflight created forbidden native-data'}
 }
 if(![IO.Path]::GetFullPath($proof.data_directory).Equals([IO.Path]::GetFullPath((Join-Path $Shared 'native-data')),[StringComparison]::OrdinalIgnoreCase)){throw 'Preflight accessed unexpected data path'}
 $dataAfter=@{};foreach($e in @(Get-MaintenanceTree $Shared -ExcludeLogs -ExcludeNativeData:$ExcludeNativeData)){$dataAfter[$e.path]=$e}
 foreach($path in $dataBefore.Keys){
  if(!$dataAfter.ContainsKey($path) -or ($dataBefore[$path]|ConvertTo-Json -Compress) -cne ($dataAfter[$path]|ConvertTo-Json -Compress)){throw ('Preflight modified existing state; explicit migration required: '+$path)}
 }
 foreach($path in $dataAfter.Keys){
  if($dataBefore.ContainsKey($path)){continue}
  $e=$dataAfter[$path]
  # Content caching is recreated by normal startup, not promoted from a trial.
  if(!$ExcludeNativeData -and $e.kind -eq 'directory' -and $path -in @('native-data','native-data/content')){continue}
  if(!$ExcludeNativeData -and $e.kind -eq 'file' -and $path -cmatch '^native-data/content/[a-f0-9]{64}\.json$'){continue}
  if(!$ExcludeNativeData -and $e.kind -eq 'file' -and $path -in @('native-data/rooms.wal','native-data/sessions.wal') -and $e.length -eq 0){continue}
  throw ('Preflight created unexpected state; explicit migration required: '+$path)
 }
 return $proof
}
function Set-NativeEnvironment([string]$Shared,$Identity) {
 $path=Join-Path $Shared '.env';$lines=@()
 if(Test-Path -LiteralPath $path){$lines=@([IO.File]::ReadAllLines($path)|Where-Object {$_ -notmatch '^\s*(SERVER_CONFIG_FILE|GAMECORE_DLL|GAMECORE_SHA256|COMBAT_CONTENT_DIR|CONFIG_POLICY)\s*='})}
 $values=@{SERVER_CONFIG_FILE=(Join-Path $layout.Shared 'host.json');GAMECORE_DLL=(Join-Path $layout.Current 'gamecore.dll');GAMECORE_SHA256=$Identity.dll_sha256;COMBAT_CONTENT_DIR=(Join-Path $layout.Current 'configs/combat');CONFIG_POLICY='server_owned'}
 foreach($key in $values.Keys){$lines+=($key+'="'+([string]$values[$key]).Replace('\','/')+'"')}
 [IO.File]::WriteAllLines($path,$lines,[Text.UTF8Encoding]::new($false))
}
function Assert-NativeStopped($State) {
 if($State.runtime_mode -ne 'WindowsService' -or [string](Get-Service -Name $State.service_name).Status -ne 'Stopped'){throw 'Native maintenance requires a fully stopped Windows service'}
}
function Get-NativeCurrentSource($CurrentState) {
 $current=[IO.Path]::GetFullPath($layout.Current).TrimEnd('\')
 Assert-ChildPath $layout.Root $current
 try{$attributes=[IO.File]::GetAttributes($current)}catch{
  $cause=$_.Exception.GetBaseException()
  if($cause -is [IO.FileNotFoundException] -or $cause -is [IO.DirectoryNotFoundException]){return $current}
  throw
 }
 if(!($attributes -band [IO.FileAttributes]::ReparsePoint)){return $current}
 # Only the root current junction is supported. Snapshot primitives still
 # reject every reparse point, including links inside an immutable release.
 $link=Get-Item -LiteralPath $current -Force -ErrorAction Stop
 if(!$link.PSIsContainer -or $link.LinkType -cne 'Junction'){throw 'Native current must be a directory or a managed release junction'}
 $targets=@($link.Target)
 if($targets.Count -ne 1 -or [string]::IsNullOrWhiteSpace([string]$targets[0])){throw 'Native current junction must have one explicit target'}
 $target=[string]$targets[0]
 if($target.StartsWith('\??\',[StringComparison]::Ordinal) -or $target.StartsWith('\\?\',[StringComparison]::Ordinal)){$target=$target.Substring(4)}
 if(![IO.Path]::IsPathRooted($target)){throw 'Native current junction target must be absolute'}
 $target=[IO.Path]::GetFullPath($target).TrimEnd('\')
 $releases=[IO.Path]::GetFullPath($layout.Releases).TrimEnd('\')
 $expected=[IO.Path]::GetFullPath((Join-Path $releases $CurrentState.current_version)).TrimEnd('\')
 Assert-ChildPath $releases $expected
 if(![IO.Path]::GetDirectoryName($expected).Equals($releases,[StringComparison]::OrdinalIgnoreCase) -or !$target.Equals($expected,[StringComparison]::OrdinalIgnoreCase)){throw 'Native current junction does not target the trusted current release'}
 # Check ancestors too: a lexically contained path must not traverse a second
 # junction/symlink before reaching the release or installation root.
 for($ancestor=$expected;$ancestor;$ancestor=[IO.Path]::GetDirectoryName($ancestor)){
  $entry=Get-Item -LiteralPath $ancestor -Force -ErrorAction Stop
  if(!$entry.PSIsContainer -or ($entry.Attributes -band [IO.FileAttributes]::ReparsePoint)){throw 'Native current junction target contains a reparse-point chain'}
 }
 $null=Get-MaintenanceTreeJSON $expected
 $identity=Test-NativeReleaseIdentity -PackageRoot $expected -AllowHistorical
 if($identity.version -cne $CurrentState.current_version){throw 'Native current junction release identity differs from trusted state'}
 return $expected
}
function Set-NativeCurrentFromRelease([string]$Release,$CurrentState) {
 Assert-NativeStopped $CurrentState
 Assert-ChildPath $layout.Releases $Release
 if(!(Test-Path -LiteralPath (Join-Path $Release 'server.exe') -PathType Leaf)){throw 'Native switch target is missing server.exe'}
 $source=Get-NativeCurrentSource $CurrentState
 $current=[IO.Path]::GetFullPath($layout.Current).TrimEnd('\')
 if(!$source.Equals($current,[StringComparison]::OrdinalIgnoreCase)){
  # Get-NativeCurrentSource has just checked the exact trusted target. Delete
  # only this directory entry; never recurse through the junction into releases.
  [IO.Directory]::Delete($current,$false)
 }
 Set-CurrentFromRelease -Layout $layout -ReleasePath $Release
}
function Assert-NativeStoredRelease($Identity) {
 $release=[IO.Path]::GetFullPath((Join-Path $layout.Releases $Identity.version))
 Assert-ChildPath $layout.Releases $release
 $stored=Test-NativeReleaseIdentity -PackageRoot $release -AllowHistorical
 foreach($name in @('version','dll_sha256','dll_build_id','verified_source_sha256','verification_audit_sha256')){
  if($stored.$name -cne $Identity.$name){throw ('Stored release differs from verified current: '+$name)}
 }
 if((Test-NativeEphemeralIdentity $stored) -ne (Test-NativeEphemeralIdentity $Identity)){throw 'Stored release room state mode differs from verified current'}
}
function Start-NativeRuntime($State,$Identity) {
 Assert-NativeStopped $State
 if($State.current_version -cne $Identity.version){throw 'Service environment target differs from deployment state'}
 Assert-NativeStoredRelease $Identity
 $release=[IO.Path]::GetFullPath((Join-Path $layout.Releases $Identity.version))
 Assert-ChildPath $layout.Releases $release
 if((Get-NativeReleaseHash (Join-Path $release 'gamecore.dll')) -cne $Identity.dll_sha256){throw 'Service environment DLL differs from verified release'}
 # SCM environment overrides .env. Refresh these selectors for every real start,
 # including forward recovery; preserve unrelated service-specific variables.
 if($State.service_name -notmatch '^[A-Za-z0-9_.-]+$'){throw 'Invalid native service name'}
 $key=[Microsoft.Win32.Registry]::LocalMachine.OpenSubKey(('SYSTEM\CurrentControlSet\Services\'+$State.service_name),$true)
 if($null -eq $key){throw 'Native service registry key is missing'}
 try{
  $values=@{SERVER_CONFIG_FILE=(Join-Path $layout.Shared 'host.json');GAMECORE_DLL=(Join-Path $release 'gamecore.dll');GAMECORE_SHA256=$Identity.dll_sha256;COMBAT_CONTENT_DIR=(Join-Path $release 'configs/combat');ENV_FILE=(Join-Path $layout.Shared '.env');LOG_DIR=(Join-Path $layout.Shared 'logs')}
  $environment=@($key.GetValue('Environment',@())|Where-Object {$_ -and $_ -notmatch '^(SERVER_CONFIG_FILE|GAMECORE_DLL|GAMECORE_SHA256|COMBAT_CONTENT_DIR|ENV_FILE|LOG_DIR)='})
  foreach($name in @($values.Keys|Sort-Object)){$environment+=($name+'='+$values[$name])}
  $key.SetValue('Environment',[string[]]$environment,[Microsoft.Win32.RegistryValueKind]::MultiString)
  $installed=@($key.GetValue('Environment',@()))
  foreach($entry in $environment){if($entry -cnotin $installed){throw 'Native service environment verification failed'}}
 }finally{$key.Dispose()}
 Start-ManagedRuntime -Layout $layout -State $State
}
function Assert-NativeEarlyRecoveryOwnership($Checkpoint,$State) {
 if($Checkpoint.may_have_served -or $Checkpoint.phase -notin @('stopping','backed_up')){return}
 if($State.current_version -cne $Checkpoint.old_state.current_version -or $State.service_name -cne $Checkpoint.old_state.service_name -or $State.runtime_mode -cne $Checkpoint.old_state.runtime_mode){throw 'Stale recovery checkpoint: deployment state changed; no service or state changes made'}
 $oldRelease=Join-Path $layout.Releases $Checkpoint.old_state.current_version
 Assert-ChildPath $layout.Releases $oldRelease
 $native=Test-Path -LiteralPath (Join-Path $layout.Current 'RELEASE_IDENTITY.json')
 if($native){
  $installed=Test-NativeReleaseIdentity -PackageRoot $layout.Current -AllowHistorical
  if($installed.version -cne $Checkpoint.old_state.current_version){throw ('Stale recovery checkpoint: current release '+$installed.version+' differs from checkpoint '+$Checkpoint.old_state.current_version+'; reconcile the verified running release instead of restoring old metadata')}
  $old=Test-NativeReleaseIdentity -PackageRoot $oldRelease -AllowHistorical
  foreach($name in @('version','dll_sha256','dll_build_id','verified_source_sha256','verification_audit_sha256')){
   if($installed.$name -cne $old.$name){throw ('Stale recovery checkpoint: current/old release '+$name+' differs; no service or state changes made')}
  }
 }else{
  if(Test-Path -LiteralPath (Join-Path $oldRelease 'RELEASE_IDENTITY.json')){throw 'Stale recovery checkpoint: current/old runtime type differs'}
  Test-ReleaseChecksums $layout.Current;Test-ReleaseChecksums $oldRelease
  if((Get-ReleaseVersion $layout.Current).SafeVersion -cne $Checkpoint.old_state.current_version -or (Get-ReleaseVersion $oldRelease).SafeVersion -cne $Checkpoint.old_state.current_version){throw 'Stale legacy recovery checkpoint: current/old release version differs'}
 }
 if([string](Get-Service -Name $State.service_name).Status -eq 'Running'){
  $version=Invoke-RestMethod -Uri ($config.health_url.TrimEnd('/')+'/version') -TimeoutSec 5
  if($version.version -cne $Checkpoint.old_state.current_version){throw 'Stale recovery checkpoint: live version differs; no service or state changes made'}
  if($native -and ($version.dll_sha256 -cne $old.dll_sha256 -or $version.module.build_id -cne $old.dll_build_id)){throw 'Stale recovery checkpoint: live DLL differs; no service or state changes made'}
 }
}
function Assert-NativeRuntimeContract($Version,$Audit) {
 Assert-NativeInstalledContractAudit $Audit
 $contract=if($Audit.PSObject.Properties.Name -contains 'current_client_contract'){$Audit.current_client_contract}else{$Audit.legacy_client_contract}
 $boundContract=$contract.PSObject.Properties.Name -contains 'contract_sha256'
 if($Version.PSObject.Properties.Name -notcontains 'runtime_identity'){
  if($boundContract){throw 'Running host lacks actual runtime_identity required by its verified contract'}
  Write-Host ('HISTORICAL LIMITED PROBE: contract='+$contract.contract+' ruleset='+$contract.ruleset+'; old host exposes DLL identity only, gameplay identity not runtime-verified')
  return
 }
 $runtime=$Version.runtime_identity
 # Only legacy 24/25 records accepted above lack an audited economy identity.
 $economy=if($boundContract){$contract.economy}else{'match-economy-v3'}
 if([string]$runtime.protocol_version -cne [string]$contract.protocol -or $runtime.contract_version -ne $contract.contract -or $runtime.ruleset_version -cne $contract.ruleset -or $runtime.economy_version -cne $economy){throw 'Running protocol/contract/Ruleset/economy identity differs from validated release'}
}
function Confirm-NativeRunning($State,$Identity,[ValidateRange(30,1800)][int]$TimeoutSeconds=180,[string]$RedisConfigurationID='') {
 $runtimeAudit=Get-Content -LiteralPath (Join-Path $layout.Current 'verification.json') -Raw -Encoding UTF8|ConvertFrom-Json
 $ephemeral=Test-NativeEphemeralIdentity $Identity
 # SCM Running precedes WAL recovery and the HTTP listener. Use a monotonic
 # startup budget rather than stopping a healthy host after only 30 seconds.
 $watch=[Diagnostics.Stopwatch]::StartNew();$reason='no response';$stage='/readyz';$nextProgress=10
 Write-Host ('NATIVE STARTUP: waiting for readiness; timeout='+$TimeoutSeconds+'s')
 while($watch.Elapsed.TotalSeconds -lt $TimeoutSeconds){
  try{
   $stage='/readyz'
   $ready=Invoke-RestMethod -Uri ($config.health_url.TrimEnd('/')+'/readyz') -TimeoutSec 5
   $stage='/version'
   $version=Invoke-RestMethod -Uri ($config.health_url.TrimEnd('/')+'/version') -TimeoutSec 5
   $stage='runtime identity'
   $checks=@(
    @{field='ready';expected=$true;actual=$ready.ready},
    @{field='engine';expected='cpp';actual=$ready.engine},
    @{field='version';expected=$State.current_version;actual=$version.version},
    @{field='dll_sha256';expected=$Identity.dll_sha256;actual=$version.dll_sha256},
    @{field='module.build_id';expected=$Identity.dll_build_id;actual=$version.module.build_id},
    @{field='transport_profile';expected='warcraft-round-v1';actual=$version.transport_profile}
   )
   $mismatch=@($checks|Where-Object {$_.actual -cne $_.expected}|ForEach-Object {$_.field+' expected='+$_.expected+' actual='+$_.actual})
   if($mismatch.Count){throw ('Running native identity mismatch: '+($mismatch -join '; '))}
   if($RedisConfigurationID){
    if($version.PSObject.Properties.Name -notcontains 'redis_configuration_version' -or $version.PSObject.Properties.Name -notcontains 'configuration_source' -or
       $version.configuration_source -cne 'redis' -or $version.redis_configuration_version -cne $RedisConfigurationID){throw 'Running host has not accepted the transaction Redis configuration'}
   }
    Assert-NativeRuntimeContract $version $runtimeAudit
    if($ephemeral){Assert-NativeEphemeralProof $version}
   Write-Host ('NATIVE READY: startup wait='+[Math]::Round($watch.Elapsed.TotalSeconds,1)+'s version='+$State.current_version)
   return
  }catch{
   $reason=$_.Exception.Message
   if($watch.Elapsed.TotalSeconds -ge $nextProgress){
    Write-Host ('NATIVE STARTUP: waited '+[Math]::Floor($watch.Elapsed.TotalSeconds)+'/'+$TimeoutSeconds+'s; waiting for '+$stage+'; last error: '+$reason)
    $nextProgress=$watch.Elapsed.TotalSeconds+10
   }
   Start-Sleep -Milliseconds 250
  }
 }
 $serviceStatus='unknown'
 try{$serviceStatus=[string](Get-Service -Name $State.service_name -ErrorAction Stop).Status}catch{}
 throw ('Native readiness failed after '+[Math]::Round($watch.Elapsed.TotalSeconds,1)+'s at '+$stage+'; service='+$serviceStatus+'; '+$reason)
}
function Complete-NativeCheckpoint($Checkpoint) {
 $Checkpoint.phase='complete';Write-MaintenanceState (Join-Path $Checkpoint.transaction 'result.json') $Checkpoint
 Remove-Item -LiteralPath $checkpointPath -Force
}
function Recover-NativeCheckpoint {
 $cp=Get-Content -LiteralPath $checkpointPath -Raw -Encoding UTF8|ConvertFrom-Json
 if($cp.kind -cne 'native-v1'){throw 'Unexpected recovery checkpoint'}
 if($cp.PSObject.Properties.Name -contains 'layout_version' -and $cp.layout_version -notin @(2,3,4)){throw 'Unsupported maintenance layout version'}
 Assert-ChildPath $layout.Root $cp.transaction
 $excludeNativeData=($cp.PSObject.Properties.Name -contains 'layout_version' -and $cp.layout_version -in @(3,4))
 if($cp.PSObject.Properties.Name -contains 'layout_version' -and $cp.layout_version -eq 4){$null=Get-NativeRedisCheckpointContext $cp}
 if($excludeNativeData){
  if($cp.PSObject.Properties.Name -notcontains 'room_state_mode' -or $cp.room_state_mode -cne 'ephemeral'){throw 'Layout 3 recovery must be bound to an ephemeral release'}
  $targetRelease=Join-Path $layout.Releases $cp.target_version
  Assert-ChildPath $layout.Releases $targetRelease
  $targetIdentity=Test-NativeReleaseIdentity -PackageRoot $targetRelease -AllowHistorical
  if(!(Test-NativeEphemeralIdentity $targetIdentity) -or $targetIdentity.version -cne $cp.target_version -or $targetIdentity.dll_sha256 -cne $cp.target_dll){throw 'Layout 3 recovery target or room state mode changed; no service or state changes made'}
 }elseif($cp.PSObject.Properties.Name -contains 'room_state_mode'){
  throw 'Room state mode requires a bound layout 3 checkpoint'
 }
 if(!$cp.may_have_served){
  $recoveryRelease=Join-Path $layout.Releases $cp.old_state.current_version
  if(Test-Path -LiteralPath (Join-Path $recoveryRelease 'RELEASE_IDENTITY.json')){$null=Test-NativeReleaseIdentity $recoveryRelease -AllowHistorical}
 }
 $state=Read-DeploymentState -Layout $layout
 # A pre-start switch may have written the new state while current still names
 # the old junction. Its ownership comes from the checkpoint, not current state.
 $currentOwner=if($cp.may_have_served){$state}else{$cp.old_state}
 $null=Get-NativeCurrentSource $currentOwner
 Assert-NativeEarlyRecoveryOwnership $cp $state
 if($cp.may_have_served){
  $forwardIdentity=Test-NativeReleaseIdentity -PackageRoot $layout.Current -AllowHistorical
  if($forwardIdentity.dll_sha256 -cne $cp.target_dll -or $forwardIdentity.version -cne $cp.target_version -or $state.current_version -cne $cp.target_version){throw 'Forward recovery target changed; no service or state changes made'}
  if([bool]$excludeNativeData -ne (Test-NativeEphemeralIdentity $forwardIdentity)){throw 'Forward recovery room state mode differs from checkpoint'}
  Assert-NativeStoredRelease $forwardIdentity
 }
 Set-Service -Name $state.service_name -StartupType Manual
 Stop-ManagedRuntime -Layout $layout -State $state;Assert-NativeStopped $state
 if($cp.may_have_served){
  Assert-NativeRedisTarget $cp
  # Never replace data after an attempted listener start. Persistent releases
  # retain the latest WAL; ephemeral releases leave all historical data untouched.
  $identity=Test-NativeReleaseIdentity -PackageRoot $layout.Current -AllowHistorical
  if($identity.dll_sha256 -cne $cp.target_dll -or $state.current_version -cne $cp.target_version){throw 'Forward recovery target changed; manual investigation required'}
  $latestBackup=Join-Path $cp.transaction ('forward-backup-'+[guid]::NewGuid().ToString('N'))
  $null=Copy-NativeStateTree $layout.Shared $latestBackup -ExcludeNativeData:$excludeNativeData
  $trial=Join-Path $cp.transaction ('forward-trial-'+[guid]::NewGuid().ToString('N'))
  $null=Copy-NativeStateTree $latestBackup $trial -ExcludeNativeData:$excludeNativeData
  $proof=Test-NativeWorkingCopy $layout.Current $trial $identity -ExcludeNativeData:$excludeNativeData
  if($cp.PSObject.Properties.Name -contains 'layout_version' -and $cp.layout_version -eq 4){Assert-NativeRedisProof $cp $proof;Assert-NativeRedisTarget $cp}
  Write-MaintenanceState (Join-Path $cp.transaction 'latest-forward-proof.json') $proof
  $acceptedRedis=if($cp.PSObject.Properties.Name -contains 'layout_version' -and $cp.layout_version -eq 4){[string]$cp.redis.target.id}else{''}
  Start-NativeRuntime $state $identity;Confirm-NativeRunning $state $identity -RedisConfigurationID $acceptedRedis
  Assert-NativeRedisTarget $cp
  Set-Service -Name $state.service_name -StartupType Automatic
  Complete-NativeCheckpoint $cp
  if($excludeNativeData){Write-Host 'NATIVE FORWARD RECOVERY SUCCEEDED; empty runtime started, historical files untouched'}else{Write-Host 'NATIVE FORWARD RECOVERY SUCCEEDED; latest state retained'}
  return
 }
 # Before the first listener start, old shared remains untouched in retired-shared.
 if($cp.PSObject.Properties.Name -contains 'layout_version' -and $cp.layout_version -eq 4){Restore-NativeRedisConfiguration $cp}
 $stable=($cp.PSObject.Properties.Name -contains 'layout_version' -and $cp.layout_version -in @(2,3,4))
 if($stable -and $cp.phase -in @('switching','activated')){
  $backup=Join-Path $cp.transaction 'backup-shared'
  if((Get-NativeStateTreeJSON $backup -ExcludeNativeData:$excludeNativeData) -cne $cp.shared_tree){throw 'Old state backup changed'}
  Assert-NativeConfigTransition $layout.Shared $cp.shared_tree $cp.candidate_tree -ExcludeNativeData:$excludeNativeData
  Set-NativeConfigFiles $backup $layout.Shared $cp.transaction
  if((Get-NativeStateTreeJSON $layout.Shared -ExcludeNativeData:$excludeNativeData) -cne $cp.shared_tree){throw 'Old config restoration incomplete'}
 }
 $retired=Join-Path $cp.transaction 'retired-shared'
 if(!$stable -and (Test-Path -LiteralPath $retired)){
  if((Get-MaintenanceTreeJSON $retired) -cne $cp.shared_tree){
   if($cp.phase -cne 'switching' -or !(Test-Path -LiteralPath $layout.Shared)){throw 'Retired state changed; refusing automatic restoration'}
   Restore-SplitMaintenanceTree $layout.Shared $retired $cp.shared_tree
   Write-Host 'SPLIT OLD STATE REASSEMBLED: all original hashes verified; retired evidence preserved'
  }else{
   if(Test-Path -LiteralPath $layout.Shared){Move-MaintenanceDirectory $layout.Shared (Join-Path $cp.transaction ('failed-shared-'+[guid]::NewGuid().ToString('N')))}
   Move-MaintenanceDirectory $retired $layout.Shared
  }
 }
 if($cp.phase -in @('switching','activated')){
  $oldRelease=Join-Path $layout.Releases $cp.old_state.current_version
  Test-ReleaseChecksums $oldRelease;Set-NativeCurrentFromRelease $oldRelease $cp.old_state
 }
 Save-DeploymentState -Layout $layout -State $cp.old_state
 $restartOld=$cp.was_running;$restoredStartup=$cp.startup
 if($excludeNativeData){
  $oldEphemeral=$false
  if(Test-Path -LiteralPath (Join-Path $layout.Current 'RELEASE_IDENTITY.json')){
   $restoredIdentity=Test-NativeReleaseIdentity $layout.Current -AllowHistorical
   $oldEphemeral=Test-NativeEphemeralIdentity $restoredIdentity
  }
  if(!$oldEphemeral){
   $restartOld=$false;$restoredStartup='Manual'
   Write-Host 'NATIVE PRE-START RECOVERY: old release restored but kept stopped; persistent history loading requires a separate manual operation'
  }
 }
 $restoredRedisContext=$null
 if($cp.PSObject.Properties.Name -contains 'layout_version' -and $cp.layout_version -eq 4){
  $restoredRedisContext=Get-NativeRedisCheckpointContext $cp
  Assert-NativeRedisSummaryEqual (Get-NativeRedisActive $restoredRedisContext.TargetRelease $restoredRedisContext.Shared) $cp.redis.old
 }
 if($restartOld){
  if(Test-Path (Join-Path $layout.Current 'RELEASE_IDENTITY.json')){
   $restoredIdentity=Test-NativeReleaseIdentity $layout.Current -AllowHistorical
   Start-NativeRuntime $cp.old_state $restoredIdentity;Confirm-NativeRunning $cp.old_state $restoredIdentity
  }else{Start-ManagedRuntime -Layout $layout -State $cp.old_state;Wait-ApplicationHealthy -HealthBaseURL $config.health_url -ExpectedVersion $cp.old_state.current_version -TimeoutSeconds 30|Out-Null}
 }
 if($null -ne $restoredRedisContext){
  Assert-NativeRedisSummaryEqual (Get-NativeRedisActive $restoredRedisContext.TargetRelease $restoredRedisContext.Shared) $cp.redis.old
 }
 Set-Service -Name $cp.old_state.service_name -StartupType $restoredStartup
 Complete-NativeCheckpoint $cp;Write-Host 'NATIVE PRE-START RECOVERY SUCCEEDED'
}
function Read-ApprovedNativeConfiguration([string]$Directory,$Identity,$State) {
 if(!(Test-NativeEphemeralIdentity $Identity) -or !$job.maintenance -or $job.action -ne 'package'){throw 'Configuration candidate requires an explicit ephemeral package maintenance deployment'}
 $directoryPath=[IO.Path]::GetFullPath($Directory)
 $approval=Get-Content -LiteralPath (Join-Path $directoryPath 'approval.json') -Raw -Encoding UTF8|ConvertFrom-Json
 if($approval.schema_version -ne 1 -or $approval.status -cne 'approved' -or !$approval.approval_ref -or $approval.artifact_sha256 -cne $job.artifact -or $approval.release_version -cne $Identity.version -or $approval.dll_sha256 -cne $Identity.dll_sha256 -or $approval.expected_current_version -cne $State.current_version){throw 'Approved configuration target differs from this deployment'}
 $reportPath=Join-Path $directoryPath 'migration-report.json'
 if((Get-NativeReleaseHash $reportPath) -cne $approval.migration_report_sha256){throw 'Approved migration report changed'}
 $report=Get-Content -LiteralPath $reportPath -Raw -Encoding UTF8|ConvertFrom-Json
 if($report.schema_version -ne 2 -or $report.status -cne 'candidate_only_not_activated'){throw 'Unsupported configuration migration report'}
 $names=@($report.files_sha256.PSObject.Properties.Name)
 if($names.Count -ne $script:NativeConfigNames.Count -or @($names|Where-Object {$_ -cnotin $script:NativeConfigNames}).Count){throw 'Configuration candidate must contain exactly host.json, gameplay.lua and economy.lua'}
 $files=@{};$sources=@{}
 foreach($name in $script:NativeConfigNames){
  $file=Get-Item -LiteralPath (Join-Path $directoryPath $name)
  if($file.PSIsContainer -or $file.Length -gt 1MB -or ($file.Attributes -band [IO.FileAttributes]::ReparsePoint)){throw ('Invalid configuration candidate file: '+$name)}
  $bytes=[IO.File]::ReadAllBytes($file.FullName)
  if((Get-NativeReleaseHashOfBytes $bytes) -cne $report.files_sha256.$name){throw ('Approved candidate bytes changed: '+$name)}
  $sourceHash=[string]$report.sources_sha256.$name
  if($sourceHash -cnotmatch '^[a-f0-9]{64}$' -or (Get-NativeReleaseHash (Join-Path $layout.Shared $name)) -cne $sourceHash){throw ('Server configuration changed since approval: '+$name)}
  $files[$name]=$bytes;$sources[$name]=$sourceHash
 }
 # Retain the approved bytes in memory so a later staging-file edit cannot
 # replace the validated candidate between backup and preflight.
 return [pscustomobject]@{files=$files;sources=$sources;evidence=$approval}
}
function Deploy-NativeRelease([string]$Release,[switch]$AllowHistorical,[string]$ConfigurationCandidate) {
 if($AllowHistorical -and $job.action -ne 'start'){throw 'Historical deployment is allowed only for explicitly starting the installed version'}
 $identity=Test-NativeReleaseIdentity -PackageRoot $Release -AllowHistorical:$AllowHistorical
 if($identity.deployment_admission -cne 'requires_native_maintenance_v1'){throw 'Package does not support the native maintenance adapter'}
 $excludeNativeData=Test-NativeEphemeralIdentity $identity
 $state=Read-DeploymentState -Layout $layout
 if($state.runtime_mode -ne 'WindowsService' -or !$state.current_version){throw 'Native upgrade requires an existing managed Windows service'}
 if($job.action -eq 'rollback'){throw 'Native rollback cannot reuse old DLL with current WAL. Deploy a validated forward-compatible package instead.'}
 if($job.action -ne 'start' -and !$job.maintenance){throw 'Explicit maintenance confirmation required'}
 $approvedConfiguration=$null
 if($ConfigurationCandidate){$approvedConfiguration=Read-ApprovedNativeConfiguration $ConfigurationCandidate $identity $state}
 $currentSource=Get-NativeCurrentSource $state
 $service=Get-Service -Name $state.service_name
 $transaction=Join-Path $layout.Root ('native-transactions/'+$JobID)
 Assert-ChildPath $layout.Root $transaction
 if(Test-Path -LiteralPath $transaction){throw 'Native transaction already exists; use checkpoint recovery'}
 New-Item -ItemType Directory -Path $transaction -Force|Out-Null
 $layoutVersion=if($excludeNativeData){3}else{2}
 $cp=[ordered]@{kind='native-v1';layout_version=$layoutVersion;candidate_tree='';phase='stopping';transaction=$transaction;old_state=$state;startup=[string]$service.StartType;was_running=([string]$service.Status -eq 'Running');may_have_served=$false;shared_tree='';target_version=$identity.version;target_dll=$identity.dll_sha256}
 if($excludeNativeData){$cp['room_state_mode']='ephemeral'}
 Write-MaintenanceState $checkpointPath $cp
 try{
  Set-Service -Name $state.service_name -StartupType Manual
  Stop-ManagedRuntime -Layout $layout -State $state;Assert-NativeStopped $state
  $cp.shared_tree=Copy-NativeStateTree $layout.Shared (Join-Path $transaction 'backup-shared') -ExcludeNativeData:$excludeNativeData
  $snapshotSource=Get-NativeCurrentSource $state
  if(!$snapshotSource.Equals($currentSource,[StringComparison]::OrdinalIgnoreCase)){throw 'Native current source changed during maintenance'}
  $null=Copy-MaintenanceTree $snapshotSource (Join-Path $transaction 'backup-current')
  $cp.phase='backed_up';Write-MaintenanceState $checkpointPath $cp
  $working=Join-Path $transaction 'working-shared';$null=Copy-NativeStateTree (Join-Path $transaction 'backup-shared') $working -ExcludeNativeData:$excludeNativeData
  # Configuration ownership is decided before any live state is touched:
  # a legacy package keeps the one-way migration, a complete package set wins.
  $packageConfig=Get-PackageNativeConfig $Release
  # External configuration selectors require explicit import; never silently
  # migrate a different JSON merely because it has the conventional name.
  $selected=''
  if(Test-Path (Join-Path $working '.env')){foreach($line in [IO.File]::ReadAllLines((Join-Path $working '.env'))){if($line -match '^\s*SERVER_CONFIG_FILE\s*=\s*(.*?)\s*$'){$selected=$Matches[1].Trim('"',"'")}}}
  $expectedConfig=Join-Path $layout.Shared 'server.json'
  if(Test-Path (Join-Path $working 'host.json')){$expectedConfig=Join-Path $layout.Shared 'host.json'}
  if($selected -and ![IO.Path]::GetFullPath($selected).Equals([IO.Path]::GetFullPath($expectedConfig),[StringComparison]::OrdinalIgnoreCase)){throw 'Explicit configuration is outside managed shared file; import and review it before migration'}
  if(Test-Path -LiteralPath (Join-Path $working 'host.json')){
   foreach($name in $script:NativeConfigNames){if(!(Test-Path -LiteralPath (Join-Path $working $name))){throw ('Incomplete authoritative server configuration: '+$name)}}
   Write-Host 'NATIVE CONFIG PRESERVED: authoritative server host/gameplay/economy'
  }elseif($packageConfig -and !(Test-Path -LiteralPath (Join-Path $working 'server.json'))){
   # Release-owned configuration: replace the three files wholesale. A removed
   # field, a renamed section and a new required key all resolve the same way,
   # so a structural change never needs a change in this deployment tool.
   foreach($name in $script:NativeConfigNames){Copy-Item -LiteralPath (Join-Path $packageConfig $name) -Destination (Join-Path $working $name) -Force}
   Write-Host ('NATIVE CONFIG FROM PACKAGE: '+($script:NativeConfigNames -join ', '))
  }elseif(!(Test-Path -LiteralPath (Join-Path $working 'host.json'))){
   $source=Join-Path $working 'server.json';$economy=Join-Path $layout.Current 'configs/combat/economy.json'
   $candidate=Join-Path $transaction 'migrated'
   $migrationArgs=@('-server-config',$source,'-economy-config',$economy,'-expected-server-sha256',(Get-NativeReleaseHash $source),'-expected-economy-sha256',(Get-NativeReleaseHash $economy),'-out',$candidate)
   $null=Invoke-NativeTool (Join-Path $Release 'configmigrate.exe') $migrationArgs @{}
   foreach($name in $script:NativeConfigNames){Copy-Item -LiteralPath (Join-Path $candidate $name) -Destination (Join-Path $working $name)}
   Write-Host 'NATIVE CONFIG FROM ONE-WAY MIGRATION OF shared/server.json'
  }else{
   Write-Host 'NATIVE CONFIG KEPT: package carries no configuration set'
  }
  if($null -ne $approvedConfiguration){
   # Original shared has already been backed up. Apply only to the disposable
   # working copy; the existing preflight/switch/recovery transaction owns activation.
   foreach($name in $script:NativeConfigNames){
    if((Get-NativeReleaseHash (Join-Path $working $name)) -cne $approvedConfiguration.sources[$name]){throw ('Configuration changed before candidate application: '+$name)}
   }
   foreach($name in $script:NativeConfigNames){[IO.File]::WriteAllBytes((Join-Path $working $name),$approvedConfiguration.files[$name])}
   Write-MaintenanceState (Join-Path $transaction 'configuration-migration.json') $approvedConfiguration.evidence
   Write-Host ('APPROVED CONFIGURATION CANDIDATE: '+$approvedConfiguration.evidence.approval_ref+'; original server configuration retained for pre-start recovery')
  }
  Write-NativeRulesDoc $working -Ephemeral:$excludeNativeData
  Set-NativeEnvironment $working $identity
  # The authority remains Redis JSON. Never reconstruct values from Lua when
  # upgrading an already Redis-managed game, and never publish before intent.
  Prepare-NativeRedisConfiguration $Release $working $identity $state $cp
  $proof=Test-NativeWorkingCopy $Release $working $identity -ExcludeNativeData:$excludeNativeData
  Assert-NativeRedisProof $cp $proof
  Assert-NativeRedisTarget $cp
  Write-MaintenanceState (Join-Path $transaction 'recovery-proof.json') $proof
  Assert-NativeStopped $state
  if((Get-NativeStateTreeJSON $layout.Shared -ExcludeNativeData:$excludeNativeData) -cne $cp.shared_tree){throw 'Active shared state changed during rehearsal'}
  # Rehearsal may create archive/cache entries in its disposable data copy.
  # Only config files enter the candidate; live WAL is never promoted/replaced.
  $candidate=Join-Path $transaction 'candidate-shared'
  $null=Copy-NativeStateTree (Join-Path $transaction 'backup-shared') $candidate -ExcludeNativeData:$excludeNativeData
  Set-NativeConfigFiles $working $candidate $transaction
  $cp.candidate_tree=Get-NativeStateTreeJSON $candidate -ExcludeNativeData:$excludeNativeData
  Assert-NativeConfigTransition $layout.Shared $cp.shared_tree $cp.candidate_tree -ExcludeNativeData:$excludeNativeData
  $cp.phase='switching';Write-MaintenanceState $checkpointPath $cp
  Set-NativeConfigFiles $candidate $layout.Shared $transaction
  if((Get-NativeStateTreeJSON $layout.Shared -ExcludeNativeData:$excludeNativeData) -cne $cp.candidate_tree){throw 'Config activation verification failed'}
  Set-NativeCurrentFromRelease $Release $state
  # Clone state; do not mutate the old-state object retained in the checkpoint.
  $next=($state|ConvertTo-Json -Depth 10)|ConvertFrom-Json
  $next.previous_version=$state.current_version;$next.current_version=$identity.version;$next.deployed_at_utc=[DateTime]::UtcNow.ToString('o')
  Save-DeploymentState -Layout $layout -State $next
  $cp.phase='activated';Write-MaintenanceState $checkpointPath $cp
  # Verify installed executable against another disposable state copy.
  $activationTrial=Join-Path $transaction 'activation-trial'
  $null=Copy-NativeStateTree $layout.Shared $activationTrial -ExcludeNativeData:$excludeNativeData
  $activationProof=Test-NativeWorkingCopy $layout.Current $activationTrial $identity -ExcludeNativeData:$excludeNativeData
  Assert-NativeRedisProof $cp $activationProof
  Assert-NativeRedisTarget $cp
  if((Get-NativeStateTreeJSON $layout.Shared -ExcludeNativeData:$excludeNativeData) -cne $cp.candidate_tree){throw 'Live state changed before start'}
  # Persist this BEFORE Start-Service: even a failed start may have served.
  $cp.may_have_served=$true;$cp.phase='start_intent';Write-MaintenanceState $checkpointPath $cp
  $acceptedRedis=if($cp.layout_version -eq 4){[string]$cp.redis.target.id}else{''}
  Start-NativeRuntime $next $identity;Confirm-NativeRunning $next $identity -RedisConfigurationID $acceptedRedis
  Assert-NativeRedisTarget $cp
  Set-Service -Name $next.service_name -StartupType Automatic
  Complete-NativeCheckpoint $cp
  Write-Host ('NATIVE DEPLOYMENT SUCCEEDED: '+$identity.version)
 }catch{
  $reason=$_.Exception.Message
  if(!$cp.may_have_served){try{Recover-NativeCheckpoint}catch{Write-Host ('RECOVERY HELD: '+$_.Exception.Message)}}
  else{try{Stop-ManagedRuntime -Layout $layout -State (Read-DeploymentState -Layout $layout)}catch{};Write-Host 'Native startup was attempted. Configuration and historical files retained; use recovery to retry the same version.'}
  throw $reason
 }
}
